from draw_ch01 import flow, SVG, TEAL


def mask():
    s = SVG('DPPO 掩码：越界之后，还要看是否继续远离行为策略', 470)
    s.text(40, 83, '先要求是响应位置；只有二元总变差 d > 阈值时，下表的方向筛选才生效。', 21)
    cols = [(390, '当前概率高于行为概率'), (880, '当前概率低于行为概率')]
    for x, title in cols:
        s.text(x, 135, title, 21, 'middle', weight='bold')
    s.text(40, 220, '正优势', 23, weight='bold')
    s.text(40, 330, '负优势', 23, weight='bold')
    for x,y,title,detail,drop in [(390,220,'屏蔽','继续增大已偏高的概率',True),
                                (880,220,'保留','增大概率，朝行为策略回归',False),
                                (390,330,'保留','减小概率，朝行为策略回归',False),
                                (880,330,'屏蔽','继续减小已偏低的概率',True)]:
        s.rect(x-225,y-43,450,85,'#fcecea' if drop else '#e5f3ee')
        s.text(x,y-12,title,24,'middle',weight='bold')
        s.text(x,y+22,detail,19,'middle')
    s.text(40, 420, '原理示意。d 等于阈值时保留；零优势贡献为零。分母仍是全部响应 token 数。', 20)
    s.save('ch09_mask.svg')


